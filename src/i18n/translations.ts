export function t(lang: LanguageCode, key: keyof TranslationKeys): string {
  return DICTIONARIES[lang]?.[key] ?? EN[key];
}

export function getLanguageDir(lang: LanguageCode): 'ltr' | 'rtl' {
  return LANGUAGES.find((l) => l.code === lang)?.dir ?? 'ltr';
}

export function formatPhaseLabel(lang: LanguageCode, phase: DisasterPhase): string {
  switch (phase) {
    case 'early_warning':
      return t(lang, 'phaseEarlyWarning');
    case 'onset':
      return t(lang, 'phaseOnset');
    case 'peak_danger':
      return t(lang, 'phasePeakDanger');
    case 'subsiding':
      return t(lang, 'phaseSubsiding');
    case 'all_clear':
      return t(lang, 'phaseAllClear');
  }
}
